import { describe, expect, it } from 'vitest';
import { agentsBlock } from '../../../src/generate/agents-md.js';
import { planGenerated } from '../../../src/generate/plan.js';
import { loadWorkspace, type WorkspaceModel } from '../../../src/workspace/load.js';
import { read, run, write } from '../../helpers/cli.js';
import { fullWorkspace, removePath } from '../../helpers/workspace.js';

const P = 'brains/brain-team-platform';
const PEOPLE = '- Name people only for responsibilities, decisions and outcomes;';
const INBOX = '- `inbox/` holds unprocessed captures and `daily/` the journal; neither needs frontmatter.';
const manifest = (ws: WorkspaceModel, id: string) => ws.brains.find((b) => b.id === id)!.manifest!;

describe('agentsBlock', () => {
  it('shared block', async () => {
    const text = agentsBlock(manifest(await loadWorkspace(await fullWorkspace()), 'brain-team-platform'));
    expect(
      text.startsWith(
        '# Platform Team\n\nCI/CD, build infrastructure, developer tooling, runners.\n\n' +
          '- Brain id: `brain-team-platform` (shared brain), owner @acme/platform.\n- Topics: ci, build, runners\n\n## Rules',
      ),
    ).toBe(true);
    expect(text).toContain('## Rules (generated by brain-mesh for brain schema 1)\n');
    expect(text).toContain(PEOPLE);
    expect(text).not.toContain(INBOX);
    expect(text.endsWith('\n')).toBe(true);
  });

  it('personal block', async () => {
    const text = agentsBlock(manifest(await loadWorkspace(await fullWorkspace()), 'personal'));
    expect(text).toContain(`${INBOX}\n`);
    expect(text).toContain('(personal brain)');
    expect(text).not.toContain(PEOPLE);
    expect(text).not.toContain('- Topics:');
  });

  it('out_of_scope line', async () => {
    const m = { ...manifest(await loadWorkspace(await fullWorkspace()), 'brain-team-platform'), out_of_scope: 'Product roadmaps' };
    expect(agentsBlock(m)).toContain('- Topics: ci, build, runners\n- Out of scope: Product roadmaps\n\n## Rules');
  });
});

describe('agentsGenerator', () => {
  it('prepends to the brain-specific part', async () => {
    const root = await fullWorkspace();
    await write(root, `${P}/AGENTS.md`, '## Brain-specific notes\n\nNothing yet.\n');
    const ws = await loadWorkspace(root);
    const file = planGenerated(ws, 'brain-team-platform').files.find((f) => f.path === `${P}/AGENTS.md`)!;
    expect(file.code).toBe('agents-md-outdated');
    expect(file.next).toBe(
      `<!-- brain-mesh:agents -->\n${agentsBlock(manifest(ws, 'brain-team-platform'))}<!-- /brain-mesh:agents -->\n\n## Brain-specific notes\n\nNothing yet.\n`,
    );
  });

  it('missing CLAUDE.md', async () => {
    const root = await fullWorkspace();
    await removePath(root, 'brains/brain-ideas/CLAUDE.md');
    const findings = (await run(['doctor', '--json'], root)).json().data.findings;
    expect(findings).toContainEqual(
      expect.objectContaining({ code: 'claude-md-missing', path: 'brains/brain-ideas/CLAUDE.md', fixable: true }),
    );
    await run(['doctor', '--fix'], root);
    expect(await read(root, 'brains/brain-ideas/CLAUDE.md')).toBe('@AGENTS.md\n');
  });

  it('description change shows up', async () => {
    const root = await fullWorkspace();
    await run(['doctor', '--fix'], root);
    const rel = `${P}/brain.yaml`;
    await write(root, rel, (await read(root, rel)).replace('developer tooling, runners.', 'developer tooling.'));
    const findings = (await run(['doctor', '--json'], root)).json().data.findings;
    expect(findings).toContainEqual(expect.objectContaining({ code: 'agents-md-outdated', path: `${P}/AGENTS.md` }));
  });
});
