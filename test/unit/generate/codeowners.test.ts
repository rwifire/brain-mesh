import { describe, expect, it } from 'vitest';
import { codeownersFor } from '../../../src/generate/codeowners.js';
import { loadWorkspace, type WorkspaceModel } from '../../../src/workspace/load.js';
import { read, run, write } from '../../helpers/cli.js';
import { fullWorkspace } from '../../helpers/workspace.js';

const P = 'brains/brain-team-platform';
const HEADER = '# generated by brain-mesh from brain.yaml and area README owners; run brain-mesh doctor --fix, do not edit\n';
const brain = (ws: WorkspaceModel, id: string) => ws.brains.find((b) => b.id === id)!;
const owners = (ws: WorkspaceModel, id: string) => codeownersFor(brain(ws, id), brain(ws, id).manifest!);

describe('codeownersFor', () => {
  it('shared brain', async () => {
    const ws = await loadWorkspace(await fullWorkspace());
    expect(owners(ws, 'brain-team-platform')).toBe(`${HEADER}* @acme/platform\n/areas/ci/ @acme/ci-team\n`);
    expect(owners(ws, 'brain-ideas')).toBe(`${HEADER}* @octo-user\n`);
  });

  it('personal brain', async () => expect(owners(await loadWorkspace(await fullWorkspace()), 'personal')).toBeNull());

  it('invalid area owner is skipped', async () => {
    const root = await fullWorkspace();
    const rel = `${P}/areas/ci/README.md`;
    await write(root, rel, (await read(root, rel)).replace('owner: "@acme/ci-team"', 'owner: "ci team"'));
    expect(owners(await loadWorkspace(root), 'brain-team-platform')).toBe(`${HEADER}* @acme/platform\n`);
  });

  it('conflicted CODEOWNERS is repaired', async () => {
    const root = await fullWorkspace();
    const rel = `${P}/CODEOWNERS`;
    await write(root, rel, `${HEADER}<<<<<<< HEAD\n* @acme/platform\n=======\n* @acme/other\n>>>>>>> pr\n`);
    const r = await run(['doctor', '--fix', '--json'], root);
    expect(r.code, r.out).toBe(0);
    expect(r.json().data.fixed).toEqual([{ code: 'codeowners-outdated', path: rel }]);
    expect(await read(root, rel)).toBe(owners(await loadWorkspace(root), 'brain-team-platform'));
  });

  it('reports a missing CODEOWNERS', async () => {
    const root = await fullWorkspace();
    const { rm } = await import('node:fs/promises');
    await rm(`${root}/${P}/CODEOWNERS`, { force: true });
    const r = await run(['doctor', '--json'], root);
    expect(r.json().data.findings).toContainEqual(expect.objectContaining({ code: 'codeowners-outdated', path: `${P}/CODEOWNERS` }));
  });
});
