import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { packageCore } from '../../../src/render/core.js';
import { gitignoreBlock, workspaceAgentsMd } from '../../../src/render/instructions.js';
import { loadWorkspace } from '../../../src/workspace/load.js';
import { read, write } from '../../helpers/cli.js';
import { fullWorkspace, removePath } from '../../helpers/workspace.js';

const CLI = 'npx -y brain-mesh-ai-workspace@0.4.2';
const template = () => readFile(join(packageCore().templatesDir, 'workspace', 'AGENTS.md'), 'utf8');
const render = async (root: string, local = [] as { name: string; text: string }[]) =>
  workspaceAgentsMd(await template(), await loadWorkspace(root), CLI, local);

describe('workspaceAgentsMd', () => {
  it('starts with the marker', async () =>
    expect((await render(await fullWorkspace())).split('\n')[0]).toBe(
      '<!-- generated by brain-mesh; do not edit. Put your own instructions in .local/*.md -->',
    ));

  it('mount table', async () => {
    const text = await render(await fullWorkspace());
    expect(text).toContain('| Brain | Mode | Published | Description |\n| --- | --- | --- | --- |\n');
    expect(text).toContain('| `personal` | personal | — | Personal notes of octo-user. |');
    expect(text).toContain('| `brain-team-platform` | contribute | yes | CI/CD, build infrastructure, developer tooling, runners. |');
    expect(text).toContain('| `brain-ideas` | contribute | no | Unpublished brain for trying out ideas. |');
    const order = ['personal', 'brain-team-platform', 'brain-handbook', 'brain-ideas'].map((id) => text.indexOf(`| \`${id}\` |`));
    expect(order.every((i) => i > 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  it('uncloned mount', async () => {
    const root = await fullWorkspace();
    await removePath(root, 'brains/brain-ideas');
    expect(await render(root)).toContain('| `brain-ideas` | contribute | no | (not cloned) |');
  });

  it('cli filled', async () => {
    const text = await render(await fullWorkspace());
    expect(text).toContain('`npx -y brain-mesh-ai-workspace@0.4.2 doctor --fix --json`');
    expect(text).not.toContain('{{');
  });

  it('local instructions appended in name order', async () =>
    expect(
      (await render(await fullWorkspace(), [
        { name: 'b.md', text: 'B' },
        { name: 'a.md', text: 'A\n' },
      ])).endsWith('\n<!-- from .local/a.md -->\nA\n\n<!-- from .local/b.md -->\nB\n'),
    ).toBe(true));

  it('pipe in a description is escaped', async () => {
    const root = await fullWorkspace();
    const rel = 'brains/brain-ideas/brain.yaml';
    await write(root, rel, (await read(root, rel)).replace('Unpublished brain for trying out ideas.', 'a | b'));
    expect(await render(root)).toContain('| `brain-ideas` | contribute | no | a \\| b |');
  });

  it('dollar patterns in a description are kept verbatim', async () => {
    const root = await fullWorkspace();
    const rel = 'brains/brain-ideas/brain.yaml';
    await write(root, rel, (await read(root, rel)).replace('Unpublished brain for trying out ideas.', () => "\"Costs in $$ and $' tail $& end\""));
    const text = await render(root);
    expect(text).toContain("| `brain-ideas` | contribute | no | Costs in $$ and $' tail $& end |");
    expect(text.match(/# AI workspace/g)).toHaveLength(1);
  });

  it('ends with exactly one newline', async () => expect(/[^\n]\n$/.test(await render(await fullWorkspace()))).toBe(true));
});

describe('gitignoreBlock', () => {
  it('lists managed paths and mounts, sorted', async () =>
    expect(gitignoreBlock(await loadWorkspace(await fullWorkspace()), ['.claude/skills/ask/', '.claude/agents/x.md'])).toBe(
      '.claude/agents/x.md\n.claude/skills/ask/\n.mesh/\nbrains/brain-handbook/\nbrains/brain-ideas/\nbrains/brain-team-platform/\nnode_modules/\n',
    ));
});

describe('the workspace AGENTS.md template', () => {
  it('says how to upgrade', async () => {
    const text = await template();
    expect(text).toContain('upgrade --dry-run --json');
    expect(text).toContain('--accept <path>');
  });
});
