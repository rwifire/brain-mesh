import { finding, type Finding } from '../doctor/finding.js';
import type { BrainManifest } from '../schemas/brain.js';
import { replaceBlock } from './blocks.js';
import { planned, type Generator, type PlannedFile } from './planned.js';

const COMMON = [
  '- Every note has YAML frontmatter with `type`, `summary` (one specific sentence) and `updated` (YYYY-MM-DD, set on every write).',
  '- Area READMEs and note, decision, howto and person notes live in `areas/<area>/`, one level deep; notes without an area go to `notes/`; maps in `maps/`, projects in `projects/`, sources in `sources/`.',
  '- File names are lowercase kebab-case and unique within the brain.',
  '- Link with relative markdown links; no wikilinks.',
  '- Search before creating a note; extend an existing note rather than adding a near-duplicate.',
  '- Do not edit inside `brain-mesh` markers or `CODEOWNERS` by hand; run `brain-mesh doctor --fix` to regenerate them.',
];
const SHARED = [
  '- Never link to the personal brain, and never copy personal notes or raw transcripts here.',
  '- Name people only for responsibilities, decisions and outcomes; never judge them. Person notes may only use the frontmatter keys type, summary, updated, name, role, team, responsibilities, contact.',
  '- Published shared brains change only through pull requests.',
];
const PERSONAL = ['- `inbox/` holds unprocessed captures and `daily/` the journal; neither needs frontmatter.'];

/** Body of the generated `AGENTS.md` block, built only from `brain.yaml`. */
export function agentsBlock(m: BrainManifest): string {
  const lines = [`# ${m.name}`, '', m.description, '', `- Brain id: \`${m.id}\` (${m.type} brain), owner ${m.owner}.`];
  if (m.topics !== undefined && m.topics.length > 0) lines.push(`- Topics: ${m.topics.join(', ')}`);
  if (m.out_of_scope !== undefined) lines.push(`- Out of scope: ${m.out_of_scope}`);
  lines.push('', `## Rules (generated by brain-mesh for brain schema ${m.schema})`, '', ...COMMON, ...(m.type === 'shared' ? SHARED : PERSONAL));
  return lines.join('\n') + '\n';
}

/** Plans the generated part of `AGENTS.md`, and `CLAUDE.md` when it is missing. */
export const agentsGenerator: Generator = (_ws, b, manifest) => {
  const files: PlannedFile[] = [];
  const problems: Finding[] = [];
  const current = b.notes.find((n) => n.path === 'AGENTS.md')?.text ?? null;
  const result = replaceBlock(current ?? '', 'agents', agentsBlock(manifest), 'prepend');
  if (result.ok) files.push(planned('agents-md-outdated', b, 'AGENTS.md', current, result.text));
  else problems.push(finding('generated-block-invalid', { brain: b.id, path: `${b.dir}/AGENTS.md`, message: result.reason }));
  if (!b.files.includes('CLAUDE.md')) files.push(planned('claude-md-missing', b, 'CLAUDE.md', null, '@AGENTS.md\n'));
  return { files, problems };
};
