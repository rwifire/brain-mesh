import type { BrainManifest } from '../schemas/brain.js';
import { Owner } from '../schemas/common.js';
import type { BrainModel } from '../workspace/load.js';
import { planned, type Generator } from './planned.js';

const HEADER = '# generated by brain-mesh from brain.yaml and area README owners; run brain-mesh doctor --fix, do not edit\n';
const byString = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** A shared brain's root `CODEOWNERS` (spec 5.7); null for a personal brain. */
export function codeownersFor(b: BrainModel, manifest: BrainManifest): string | null {
  if (manifest.type === 'personal') return null;
  const areas: [string, string][] = [];
  for (const n of b.notes) {
    const m = /^areas\/([^/]+)\/README\.md$/.exec(n.path);
    const owner = Owner.safeParse(n.frontmatter?.owner);
    if (m && owner.success) areas.push([m[1]!, owner.data]);
  }
  areas.sort((x, y) => byString(x[0], y[0]));
  return HEADER + `* ${manifest.owner}\n` + areas.map(([a, o]) => `/areas/${a}/ ${o}\n`).join('');
}

/** Plans `CODEOWNERS`; the whole file is managed, so it is always fully regenerated. */
export const codeownersGenerator: Generator = (_ws, b, manifest) => {
  const next = codeownersFor(b, manifest);
  if (next === null) return { files: [], problems: [] };
  return { files: [planned('codeowners-outdated', b, 'CODEOWNERS', b.codeownersText, next)], problems: [] };
};
