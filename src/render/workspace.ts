import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, rmdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, posix } from 'node:path';
import { replaceBlock, withEol } from '../generate/blocks.js';
import { CliError, ErrorCode, ExitCode, type Warning } from '../output.js';
import { loadWorkspace, type WorkspaceModel } from '../workspace/load.js';
import { claudeAgent, copilotAgent, fill, skillFiles } from './clients.js';
import { overlay, packageCore, readAgents, readSkills, type AgentSource, type CoreSource, type SkillSource, type SourceProblem } from './core.js';
import { gitignoreBlock, workspaceAgentsMd, type LocalInstruction } from './instructions.js';

export type EntryKind = 'managed' | 'seed' | 'block';

export interface RenderEntry {
  /** Workspace-relative POSIX path. */
  path: string;
  kind: EntryKind;
  /** File bytes; for `block`, the block body. */
  content: Buffer;
  /** Client skill folder (`.claude/skills/<n>/`) whose files are owned or refused together. */
  group?: string;
}

export interface RecordEntry {
  path: string;
  kind: EntryKind;
  /** sha256 of what brain-mesh rendered (the block body for `block`). */
  sha256: string;
}

export interface RenderRecord {
  version: 1;
  /** The pinned core version the files were rendered for. */
  brain_mesh: string;
  /** Sorted by path. */
  files: RecordEntry[];
}

export const RECORD_PATH = '.mesh/render.json';

export interface CoreTemplates {
  agentsMd: string;
  gitattributes: string;
  obsidianApp: string;
  /** `<type>.md` → text; empty when the core has no note templates. */
  notes: Map<string, string>;
}

export interface RenderResult {
  written: string[];
  removed: string[];
  record: RenderRecord;
  warnings: Warning[];
}

const MARKER = 'generated by brain-mesh';
const byString = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const utf8 = (s: string) => Buffer.from(s, 'utf8');
const sha256 = (b: Buffer) => createHash('sha256').update(b).digest('hex');
const lf = (b: Buffer) => b.toString('utf8').replace(/\r\n/g, '\n');
const reason = (err: unknown) => (err instanceof Error ? err.message.split('\n')[0]! : String(err));

/** Every managed, seed and block entry of the workspace (plan Rulings 3, 6, 7). */
export function planWorkspace(
  ws: WorkspaceModel,
  core: { skills: SkillSource[]; agents: AgentSource[]; templates: CoreTemplates },
  local: { skills: SkillSource[]; agents: AgentSource[]; instructions: LocalInstruction[] },
): RenderEntry[] {
  if (ws.mesh === null) throw new Error('planWorkspace needs a valid mesh.yaml');
  const cli = `npx -y brain-mesh@${ws.mesh.brain_mesh}`;
  const out: RenderEntry[] = [];
  const managed = (path: string, content: Buffer, group?: string) =>
    out.push(group === undefined ? { path, kind: 'managed', content } : { path, kind: 'managed', content, group });

  managed('AGENTS.md', utf8(workspaceAgentsMd(core.templates.agentsMd, ws, cli, local.instructions)));
  managed('CLAUDE.md', utf8('@AGENTS.md\n'));
  for (const s of core.skills) for (const [f, b] of s.files) managed(`.mesh/skills/${s.name}/${f}`, b);
  for (const a of core.agents) managed(`.mesh/agents/${a.name}.md`, utf8(agentSource(a)));
  for (const [name, text] of core.templates.notes) managed(`.mesh/templates/notes/${name}`, utf8(text));

  const clientPaths: string[] = [];
  for (const s of overlay(core.skills, local.skills)) {
    for (const client of ['.claude', '.github']) {
      const folder = `${client}/skills/${s.name}/`;
      clientPaths.push(folder);
      for (const [f, b] of skillFiles(s, cli)) managed(`${folder}${f}`, b, folder);
    }
  }
  for (const a of overlay(core.agents, local.agents)) {
    managed(`.claude/agents/${a.name}.md`, utf8(claudeAgent(a, cli)));
    managed(`.github/agents/${a.name}.agent.md`, utf8(copilotAgent(a, cli)));
    clientPaths.push(`.claude/agents/${a.name}.md`, `.github/agents/${a.name}.agent.md`);
  }

  out.push({ path: '.gitattributes', kind: 'seed', content: utf8(core.templates.gitattributes) });
  out.push({ path: 'brains/.obsidian/app.json', kind: 'seed', content: utf8(core.templates.obsidianApp) });
  out.push({ path: '.gitignore', kind: 'block', content: utf8(gitignoreBlock(ws, clientPaths)) });
  return out.sort((x, y) => byString(x.path, y.path));
}

/** The core copy of an agent in its source format (`.mesh/agents/<n>.md`), unfilled. */
function agentSource(a: AgentSource): string {
  return `---\nname: ${a.name}\ndescription: ${JSON.stringify(a.description)}\ntools: [${a.tools.join(', ')}]\n---\n${a.body}`;
}

async function readText(path: string): Promise<string | null> {
  try {
    return await readFile(path, 'utf8');
  } catch {
    return null;
  }
}

async function readCoreTemplates(dir: string): Promise<CoreTemplates> {
  const need = async (rel: string) => {
    const text = await readText(join(dir, ...rel.split('/')));
    if (text === null) throw new CliError(ErrorCode.Internal, `core template missing: templates/${rel}`);
    return text;
  };
  const notes = new Map<string, string>();
  let names: string[] = [];
  try {
    names = (await readdir(join(dir, 'notes'))).filter((n) => n.endsWith('.md')).sort(byString);
  } catch {
    names = [];
  }
  for (const n of names) notes.set(n, (await readText(join(dir, 'notes', n)))!);
  return {
    agentsMd: await need('workspace/AGENTS.md'),
    gitattributes: await need('workspace/gitattributes'),
    obsidianApp: await need('workspace/obsidian-app.json'),
    notes,
  };
}

async function readLocalInstructions(root: string): Promise<LocalInstruction[]> {
  let entries;
  try {
    entries = await readdir(join(root, '.local'), { withFileTypes: true });
  } catch {
    return [];
  }
  const out: LocalInstruction[] = [];
  for (const e of entries.filter((x) => x.isFile() && x.name.endsWith('.md'))) {
    out.push({ name: e.name, text: (await readText(join(root, '.local', e.name))) ?? '' });
  }
  return out;
}

async function readRecord(root: string): Promise<RenderRecord | null> {
  const text = await readText(join(root, ...RECORD_PATH.split('/')));
  if (text === null) return null;
  try {
    const r = JSON.parse(text) as RenderRecord;
    return Array.isArray(r.files) ? r : null;
  } catch {
    return null;
  }
}

type Kind = 'missing' | 'file' | 'dir' | 'link' | 'other';
async function kindOf(abs: string): Promise<Kind> {
  try {
    const s = await lstat(abs);
    return s.isSymbolicLink() ? 'link' : s.isFile() ? 'file' : s.isDirectory() ? 'dir' : 'other';
  } catch {
    return 'missing';
  }
}

/** True when `rel` or one of its parent folders inside the workspace is a symbolic link (or junction). */
async function throughLink(root: string, rel: string): Promise<boolean> {
  const parts = rel.split('/');
  for (let i = 1; i <= parts.length; i++) {
    const k = await kindOf(join(root, ...parts.slice(0, i)));
    if (k === 'link') return true;
    if (k === 'missing') return false;
  }
  return false;
}

/** Every regular file under a folder, as workspace-relative POSIX paths. */
async function filesUnder(root: string, rel: string): Promise<string[]> {
  const out: string[] = [];
  let entries;
  try {
    entries = await readdir(join(root, ...rel.split('/')), { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const child = posix.join(rel, e.name);
    if (e.isDirectory()) out.push(...(await filesUnder(root, child)));
    else out.push(child);
  }
  return out;
}

/**
 * Renders the workspace's managed files and writes `.mesh/render.json` (spec 4, 9.2).
 * Writes only paths that are brain-mesh's (plan Ruling 4), never through a link, and
 * removes managed entries of the previous record that are no longer rendered.
 */
export async function renderWorkspace(root: string, opts: { core?: CoreSource } = {}): Promise<RenderResult> {
  if ((await kindOf(join(root, 'mesh.yaml'))) !== 'file') {
    throw new CliError(ErrorCode.NoWorkspace, `no mesh.yaml in ${root}`, ExitCode.Failure);
  }
  const ws = await loadWorkspace(root);
  if (ws.mesh === null) throw new CliError(ErrorCode.NoWorkspace, `mesh.yaml is invalid: ${ws.meshError}`, ExitCode.Failure);
  const core = opts.core ?? packageCore();
  const warnings: Warning[] = [];
  const report = (code: string, where: string) => (p: SourceProblem) =>
    warnings.push({ code, message: `${where}/${p.path}: ${p.message}` });

  const coreSkills = await readSkills(core.skillsDir, 'core');
  const coreAgents = await readAgents(core.agentsDir, 'core');
  const localSkills = await readSkills(join(root, '.local', 'skills'), 'local');
  const localAgents = await readAgents(join(root, '.local', 'agents'), 'local');
  coreSkills.problems.forEach(report('W_SKILL_INVALID', 'core skills'));
  coreAgents.problems.forEach(report('W_AGENT_INVALID', 'core agents'));
  localSkills.problems.forEach(report('W_SKILL_INVALID', '.local/skills'));
  localAgents.problems.forEach(report('W_AGENT_INVALID', '.local/agents'));

  const entries = planWorkspace(
    ws,
    { skills: coreSkills.skills, agents: coreAgents.agents, templates: await readCoreTemplates(core.templatesDir) },
    { skills: localSkills.skills, agents: localAgents.agents, instructions: await readLocalInstructions(root) },
  );
  const prev = await readRecord(root);
  const prevPaths = new Set((prev?.files ?? []).map((f) => f.path));
  const abs = (rel: string) => join(root, ...rel.split('/'));
  const taken = (rel: string, why: string) =>
    warnings.push({ code: 'W_RENDER_PATH_TAKEN', message: `${rel} is not brain-mesh's (${why}); left as it is` });

  // A client skill folder is brain-mesh's when it was recorded, does not exist, or holds only what would be rendered.
  const refusedGroups = new Set<string>();
  for (const group of new Set(entries.flatMap((e) => (e.group === undefined ? [] : [e.group])))) {
    const dir = group.slice(0, -1);
    if (await throughLink(root, dir)) {
      refusedGroups.add(group);
      taken(group, 'a symbolic link');
      continue;
    }
    if ([...prevPaths].some((p) => p.startsWith(group)) || (await kindOf(abs(dir))) === 'missing') continue;
    const rendered = new Map(entries.filter((e) => e.group === group).map((e) => [e.path, e.content]));
    let ours = true;
    for (const f of await filesUnder(root, dir)) {
      const want = rendered.get(f);
      const have = want === undefined ? null : await readFile(abs(f)).catch(() => null);
      if (want === undefined || have === null || lf(have) !== lf(want)) ours = false;
    }
    if (!ours) {
      refusedGroups.add(group);
      taken(group, 'the folder holds files brain-mesh did not render');
    }
  }

  const written: string[] = [];
  const recorded: RecordEntry[] = [];
  const put = async (e: RenderEntry, current: Buffer | null, next: Buffer): Promise<void> => {
    try {
      await mkdir(dirname(abs(e.path)), { recursive: true });
      if (current === null) await writeFile(abs(e.path), next, { flag: 'wx' });
      else await writeFile(abs(e.path), next);
      written.push(e.path);
    } catch (err) {
      warnings.push({ code: 'W_WRITE_FAILED', message: `could not write ${e.path}: ${reason(err)}` });
    }
  };

  for (const e of entries) {
    if (e.group !== undefined && refusedGroups.has(e.group)) continue;
    const k = await kindOf(abs(e.path));
    if (k === 'link' || (await throughLink(root, e.path))) {
      taken(e.path, 'a symbolic link');
      continue;
    }
    if (k === 'dir' || k === 'other') {
      taken(e.path, 'not a regular file');
      continue;
    }
    const current = k === 'file' ? await readFile(abs(e.path)) : null;

    if (e.kind === 'seed') {
      if (current === null) await put(e, null, e.content);
      recorded.push({ path: e.path, kind: 'seed', sha256: sha256(e.content) });
      continue;
    }
    if (e.kind === 'block') {
      const text = current === null ? '' : current.toString('utf8');
      const result = replaceBlock(text, 'managed', e.content.toString('utf8'), 'append', 'hash');
      if (!result.ok) {
        warnings.push({ code: 'W_RENDER_BLOCK_INVALID', message: `${e.path}: ${result.reason}` });
        continue;
      }
      const next = withEol(result.text, current === null ? null : text);
      if (next !== text || current === null) await put(e, current, utf8(next));
      recorded.push({ path: e.path, kind: 'block', sha256: sha256(e.content) });
      continue;
    }
    // managed
    if (current !== null && lf(current) === lf(e.content)) {
      recorded.push({ path: e.path, kind: 'managed', sha256: sha256(e.content) });
      continue;
    }
    const ours = current === null || prevPaths.has(e.path) || e.group !== undefined || current.toString('utf8').includes(MARKER);
    if (!ours) {
      taken(e.path, 'the file exists and was not rendered by brain-mesh');
      continue;
    }
    const isText = !e.content.includes(0);
    const next = current !== null && isText ? utf8(withEol(e.content.toString('utf8'), current.toString('utf8'))) : e.content;
    await put(e, current, next);
    recorded.push({ path: e.path, kind: 'managed', sha256: sha256(e.content) });
  }

  // Managed entries rendered last time and not any more are removed; nothing else is.
  const now = new Set(entries.map((e) => e.path));
  const removed: string[] = [];
  for (const old of prev?.files ?? []) {
    if (old.kind !== 'managed' || now.has(old.path)) continue;
    if (await throughLink(root, old.path)) continue;
    if ((await kindOf(abs(old.path))) !== 'file') continue;
    try {
      await unlink(abs(old.path));
      removed.push(old.path);
      await pruneEmpty(root, posix.dirname(old.path));
    } catch (err) {
      warnings.push({ code: 'W_WRITE_FAILED', message: `could not remove ${old.path}: ${reason(err)}` });
      recorded.push(old);
    }
  }

  const record: RenderRecord = {
    version: 1,
    brain_mesh: ws.mesh.brain_mesh,
    files: recorded.sort((x, y) => byString(x.path, y.path)),
  };
  const recordText = JSON.stringify(record, null, 2) + '\n';
  if ((await readText(abs(RECORD_PATH))) !== recordText) {
    try {
      await mkdir(dirname(abs(RECORD_PATH)), { recursive: true });
      await writeFile(abs(RECORD_PATH), recordText, 'utf8');
      written.push(RECORD_PATH);
    } catch (err) {
      warnings.push({ code: 'W_WRITE_FAILED', message: `could not write ${RECORD_PATH}: ${reason(err)}` });
    }
  }
  return { written: written.sort(byString), removed: removed.sort(byString), record, warnings };
}

/** Removes empty folders upwards from `rel`, keeping the top two levels (`.claude/skills`, `.mesh/agents`, …). */
async function pruneEmpty(root: string, rel: string): Promise<void> {
  let dir = rel;
  while (dir.split('/').length > 2) {
    try {
      await rmdir(join(root, ...dir.split('/')));
    } catch {
      return;
    }
    dir = posix.dirname(dir);
  }
}
