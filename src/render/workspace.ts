export type EntryKind = 'managed' | 'seed' | 'block';

export interface RenderEntry {
  /** Workspace-relative POSIX path. */
  path: string;
  kind: EntryKind;
  /** File bytes; for `block`, the block body. */
  content: Buffer;
  /** Client skill folder (`.claude/skills/<n>/`) whose files are owned or refused together. */
  group?: string;
  /** A skill file other than `SKILL.md`: compared and written byte for byte, never line-ending adjusted. */
  bytes?: boolean;
  /** Needs the executable bit where the platform has modes (the pre-commit hook). */
  executable?: boolean;
}

export interface RecordEntry {
  path: string;
  kind: EntryKind;
  /** sha256 of what brain-mesh rendered (the block body for `block`). */
  sha256: string;
}

export interface RenderRecord {
  version: 1;
  /** The pinned core version the files were rendered for. */
  brain_mesh: string;
  /** Sorted by path. */
  files: RecordEntry[];
}

export const RECORD_PATH = '.mesh/render.json';

export interface CoreTemplates {
  agentsMd: string;
  gitattributes: string;
  obsidianApp: string;
  /** `<type>.md` → text; empty when the core has no note templates. */
  notes: Map<string, string>;
  /** `.mesh/hooks/<name>` → text; empty when the core has no hooks. */
  hooks: Map<string, string>;
}

export interface RenderOptions {
  core?: CoreSource;
  /** Renders for this core version instead of `mesh.yaml`'s pin: `{{cli}}` and the record use it. */
  pin?: string;
  /** False: change nothing on disk (the record included) and report what would change. */
  write?: boolean;
  /** Upgrade mode for seeds (chunk 11 plan, decision 4): edited seeds are kept unless accepted. */
  seeds?: { accept: ReadonlySet<string> };
}

/** A managed or seed path whose content changes (or would change), or an edited seed that is kept. */
export interface RenderChange {
  path: string;
  kind: EntryKind;
  /** The file's text before, or null when it did not exist. */
  before: string | null;
  /** What brain-mesh renders there now (for a kept seed: what it would have written). */
  after: string;
  status: 'written' | 'updated' | 'accepted' | 'kept';
  /** The record has the path and the file no longer matches its recorded sha256. */
  handEdited: boolean;
}

export interface RenderResult {
  written: string[];
  removed: string[];
  record: RenderRecord;
  /** Sorted by path. */
  changes: RenderChange[];
  /** The record before this render, or null when there was none. */
  previous: RenderRecord | null;
  warnings: Warning[];
}

const MARKER = 'generated by brain-mesh';
const byString = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const utf8 = (s: string) => Buffer.from(s, 'utf8');
const sha256 = (b: Buffer) => createHash('sha256').update(b).digest('hex');
const lf = (b: Buffer) => b.toString('utf8').replace(/\r\n/g, '\n');
const reason = (err: unknown) => (err instanceof Error ? err.message.split('\n')[0]! : String(err));

/** Every managed, seed and block entry of the workspace (plan Rulings 3, 6, 7). */
export function planWorkspace(
  ws: WorkspaceModel,
  core: { skills: SkillSource[]; agents: AgentSource[]; templates: CoreTemplates },
  local: { skills: SkillSource[]; agents: AgentSource[]; instructions: LocalInstruction[] },
): RenderEntry[] {
  if (ws.mesh === null) throw new Error('planWorkspace needs a valid mesh.yaml');
  const cli = `npx -y brain-mesh-ai-workspace@${ws.mesh.brain_mesh}`;
  const out: RenderEntry[] = [];
  const managed = (path: string, content: Buffer, group?: string, bytes = false) => {
    const e: RenderEntry = { path, kind: 'managed', content };
    if (group !== undefined) e.group = group;
    if (bytes) e.bytes = true;
    out.push(e);
  };

  managed('AGENTS.md', utf8(workspaceAgentsMd(core.templates.agentsMd, ws, cli, local.instructions)));
  managed('CLAUDE.md', utf8('@AGENTS.md\n'));
  for (const s of core.skills) for (const [f, b] of s.files) managed(`.mesh/skills/${s.name}/${f}`, b, undefined, f !== 'SKILL.md');
  for (const a of core.agents) managed(`.mesh/agents/${a.name}.md`, utf8(agentSource(a)));
  for (const [name, text] of core.templates.notes) managed(`.mesh/templates/notes/${name}`, utf8(text));
  for (const [name, text] of core.templates.hooks) {
    const e: RenderEntry = { path: `.mesh/hooks/${name}`, kind: 'managed', content: utf8(text), bytes: true };
    if (name === 'pre-commit') e.executable = true;
    out.push(e);
  }

  const clientPaths: string[] = [];
  for (const s of overlay(core.skills, local.skills)) {
    for (const client of ['.claude', '.github']) {
      const folder = `${client}/skills/${s.name}/`;
      clientPaths.push(folder);
      for (const [f, b] of skillFiles(s, cli)) managed(`${folder}${f}`, b, folder, f !== 'SKILL.md');
    }
  }
  for (const a of overlay(core.agents, local.agents)) {
    managed(`.claude/agents/${a.name}.md`, utf8(claudeAgent(a, cli)));
    managed(`.github/agents/${a.name}.agent.md`, utf8(copilotAgent(a, cli)));
    clientPaths.push(`.claude/agents/${a.name}.md`, `.github/agents/${a.name}.agent.md`);
  }

  out.push({ path: '.gitattributes', kind: 'seed', content: utf8(core.templates.gitattributes) });
  out.push({ path: 'brains/.obsidian/app.json', kind: 'seed', content: utf8(core.templates.obsidianApp) });
  out.push({ path: '.gitignore', kind: 'block', content: utf8(gitignoreBlock(ws, clientPaths)) });
  return out.sort((x, y) => byString(x.path, y.path));
}

/** The core copy of an agent in its source format (`.mesh/agents/<n>.md`), unfilled. */
export function agentSource(a: AgentSource): string {
  return `---\nname: ${a.name}\ndescription: ${JSON.stringify(a.description)}\ntools: [${a.tools.join(', ')}]\n---\n${a.body}`;
}

/** Sets mode 0o755 when no execute bit is set; a no-op where the platform has no modes. */
async function makeExecutable(path: string): Promise<void> {
  try {
    if (((await stat(path)).mode & 0o111) === 0) await chmod(path, 0o755);
  } catch {
    // a failed write was already reported
  }
}

async function readText(path: string): Promise<string | null> {
  try {
    return await readFile(path, 'utf8');
  } catch {
    return null;
  }
}

async function readCoreTemplates(dir: string): Promise<CoreTemplates> {
  const need = async (rel: string) => {
    const text = await readText(join(dir, ...rel.split('/')));
    if (text === null) throw new CliError(ErrorCode.Internal, `core template missing: templates/${rel}`);
    return text;
  };
  const notes = new Map<string, string>();
  let names: string[] = [];
  try {
    names = (await readdir(join(dir, 'notes'))).filter((n) => n.endsWith('.md')).sort(byString);
  } catch {
    names = [];
  }
  for (const n of names) notes.set(n, (await readText(join(dir, 'notes', n)))!);
  const hooks = new Map<string, string>();
  let hookNames: string[] = [];
  try {
    hookNames = (await readdir(join(dir, 'hooks'), { withFileTypes: true })).filter((d) => d.isFile()).map((d) => d.name).sort(byString);
  } catch {
    hookNames = [];
  }
  for (const n of hookNames) hooks.set(n, (await readText(join(dir, 'hooks', n)))!);
  return {
    agentsMd: await need('workspace/AGENTS.md'),
    gitattributes: await need('workspace/gitattributes'),
    obsidianApp: await need('workspace/obsidian-app.json'),
    notes,
    hooks,
  };
}

async function readLocalInstructions(root: string): Promise<LocalInstruction[]> {
  let entries;
  try {
    entries = await readdir(join(root, '.local'), { withFileTypes: true });
  } catch {
    return [];
  }
  const out: LocalInstruction[] = [];
  for (const e of entries.filter((x) => x.isFile() && x.name.endsWith('.md'))) {
    out.push({ name: e.name, text: (await readText(join(root, '.local', e.name))) ?? '' });
  }
  return out;
}

const KINDS = new Set<unknown>(['managed', 'seed', 'block']);

/** A workspace-relative POSIX path that cannot leave the workspace. */
function safePath(p: unknown): p is string {
  if (typeof p !== 'string' || p === '' || p.startsWith('/') || p.includes('\\') || p.includes(':')) return false;
  return p.split('/').every((seg) => seg !== '' && seg !== '.' && seg !== '..');
}

/** The previous record; entries that are malformed or point outside the workspace are dropped. */
export async function readRecord(root: string): Promise<RenderRecord | null> {
  const text = await readText(join(root, ...RECORD_PATH.split('/')));
  if (text === null) return null;
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch {
    return null;
  }
  const files = (raw as { files?: unknown } | null)?.files;
  if (!Array.isArray(files)) return null;
  const valid = files.filter(
    (f): f is RecordEntry =>
      f !== null && typeof f === 'object' && safePath(f.path) && KINDS.has(f.kind) && typeof f.sha256 === 'string',
  );
  return { version: 1, brain_mesh: String((raw as { brain_mesh?: unknown }).brain_mesh ?? ''), files: valid };
}

/** Paths stale removal may delete: only what brain-mesh renders as `managed`. */
function removable(p: string): boolean {
  return (
    p === 'AGENTS.md' ||
    p === 'CLAUDE.md' ||
    ['.mesh/', '.claude/skills/', '.claude/agents/', '.github/skills/', '.github/agents/'].some((prefix) => p.startsWith(prefix))
  );
}

type Kind = 'missing' | 'file' | 'dir' | 'link' | 'other';
async function kindOf(abs: string): Promise<Kind> {
  try {
    const s = await lstat(abs);
    return s.isSymbolicLink() ? 'link' : s.isFile() ? 'file' : s.isDirectory() ? 'dir' : 'other';
  } catch {
    return 'missing';
  }
}

/** True when `rel` or one of its parent folders inside the workspace is a symbolic link (or junction). */
async function throughLink(root: string, rel: string): Promise<boolean> {
  const parts = rel.split('/');
  for (let i = 1; i <= parts.length; i++) {
    const k = await kindOf(join(root, ...parts.slice(0, i)));
    if (k === 'link') return true;
    if (k === 'missing') return false;
  }
  return false;
}

/** Every regular file under a folder, as workspace-relative POSIX paths. */
async function filesUnder(root: string, rel: string): Promise<string[]> {
  const out: string[] = [];
  let entries;
  try {
    entries = await readdir(join(root, ...rel.split('/')), { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const child = posix.join(rel, e.name);
    if (e.isDirectory()) out.push(...(await filesUnder(root, child)));
    else out.push(child);
  }
  return out;
}

/**
 * Renders the workspace's managed files and writes `.mesh/render.json` (spec 4, 9.2).
 * Writes only paths that are brain-mesh's (plan Ruling 4), never through a link, and
 * removes managed entries of the previous record that are no longer rendered.
 */
export async function renderWorkspace(root: string, opts: RenderOptions = {}): Promise<RenderResult> {
  if ((await kindOf(join(root, 'mesh.yaml'))) !== 'file') {
    throw new CliError(ErrorCode.NoWorkspace, `no mesh.yaml in ${root}`, ExitCode.Failure);
  }
  const loaded = await loadWorkspace(root);
  if (loaded.mesh === null) throw new CliError(ErrorCode.NoWorkspace, `mesh.yaml is invalid: ${loaded.meshError}`, ExitCode.Failure);
  const ws: WorkspaceModel = opts.pin === undefined ? loaded : { ...loaded, mesh: { ...loaded.mesh, brain_mesh: opts.pin } };
  const mesh = ws.mesh!;
  const doWrite = opts.write !== false;
  const core = opts.core ?? packageCore();
  const warnings: Warning[] = [];
  const report = (code: string, where: string) => (p: SourceProblem) =>
    warnings.push({ code, message: `${where}/${p.path}: ${p.message}` });

  const coreSkills = await readSkills(core.skillsDir, 'core');
  const coreAgents = await readAgents(core.agentsDir, 'core');
  const localSkills = await readSkills(join(root, '.local', 'skills'), 'local');
  const localAgents = await readAgents(join(root, '.local', 'agents'), 'local');
  coreSkills.problems.forEach(report('W_SKILL_INVALID', 'core skills'));
  coreAgents.problems.forEach(report('W_AGENT_INVALID', 'core agents'));
  localSkills.problems.forEach(report('W_SKILL_INVALID', '.local/skills'));
  localAgents.problems.forEach(report('W_AGENT_INVALID', '.local/agents'));

  const entries = planWorkspace(
    ws,
    { skills: coreSkills.skills, agents: coreAgents.agents, templates: await readCoreTemplates(core.templatesDir) },
    { skills: localSkills.skills, agents: localAgents.agents, instructions: await readLocalInstructions(root) },
  );
  const prev = await readRecord(root);
  const prevPaths = new Set((prev?.files ?? []).map((f) => f.path));
  const prevEntry = new Map((prev?.files ?? []).map((f) => [f.path, f]));
  const abs = (rel: string) => join(root, ...rel.split('/'));
  const taken = (rel: string, why: string) =>
    warnings.push({ code: 'W_RENDER_PATH_TAKEN', message: `${rel} is not brain-mesh's (${why}); left as it is` });

  // A client skill folder is brain-mesh's when it was recorded, does not exist, or holds only what would be rendered.
  const refusedGroups = new Set<string>();
  for (const group of new Set(entries.flatMap((e) => (e.group === undefined ? [] : [e.group])))) {
    const dir = group.slice(0, -1);
    if (await throughLink(root, dir)) {
      refusedGroups.add(group);
      taken(group, 'a symbolic link');
      continue;
    }
    if ([...prevPaths].some((p) => p.startsWith(group)) || (await kindOf(abs(dir))) === 'missing') continue;
    const rendered = new Map(entries.filter((e) => e.group === group).map((e) => [e.path, e.content]));
    const same = (e: RenderEntry, have: Buffer) => (e.bytes ? have.equals(e.content) : lf(have) === lf(e.content));
    let ours = true;
    for (const f of await filesUnder(root, dir)) {
      const want = rendered.get(f);
      const entry = entries.find((e) => e.path === f);
      const have = want === undefined ? null : await readFile(abs(f)).catch(() => null);
      if (entry === undefined || have === null || !same(entry, have)) ours = false;
    }
    if (!ours) {
      refusedGroups.add(group);
      taken(group, 'the folder holds files brain-mesh did not render');
    }
  }

  const written: string[] = [];
  const recorded: RecordEntry[] = [];
  const changes: RenderChange[] = [];
  /** Writes `next`; true on success (or, without `write`, always: nothing touches disk). */
  const put = async (e: RenderEntry, current: Buffer | null, next: Buffer): Promise<boolean> => {
    if (!doWrite) {
      written.push(e.path);
      return true;
    }
    try {
      await mkdir(dirname(abs(e.path)), { recursive: true });
      if (current === null) await writeFile(abs(e.path), next, { flag: 'wx' });
      else await writeFile(abs(e.path), next);
      written.push(e.path);
      return true;
    } catch (err) {
      warnings.push({ code: 'W_WRITE_FAILED', message: `could not write ${e.path}: ${reason(err)}` });
      return false;
    }
  };
  /** Records `e` as rendered; after a failed write the previous entry (if any) stays, so the record matches disk. */
  const keep = (e: RenderEntry, ok: boolean, sha: string) => {
    if (ok) recorded.push({ path: e.path, kind: e.kind, sha256: sha });
    else if (prevEntry.has(e.path)) recorded.push(prevEntry.get(e.path)!);
  };
  /** True when the record has `path` and `current` no longer matches its recorded sha256 (line endings ignored for text). */
  const edited = (e: RenderEntry, current: Buffer) => {
    const old = prevEntry.get(e.path);
    return old !== undefined && (e.bytes ? sha256(current) : sha256(utf8(lf(current)))) !== old.sha256;
  };
  const change = (e: RenderEntry, current: Buffer | null, after: Buffer, status: RenderChange['status'], handEdited: boolean) =>
    changes.push({ path: e.path, kind: e.kind, before: current === null ? null : current.toString('utf8'), after: after.toString('utf8'), status, handEdited });

  const blocks = entries.filter((e) => e.kind === 'block');
  for (const e of [...entries.filter((x) => x.kind !== 'block'), ...blocks]) {
    if (e.group !== undefined && refusedGroups.has(e.group)) continue;
    const k = await kindOf(abs(e.path));
    if (k === 'link' || (await throughLink(root, e.path))) {
      taken(e.path, 'a symbolic link');
      continue;
    }
    if (k === 'dir' || k === 'other') {
      taken(e.path, 'not a regular file');
      continue;
    }
    const current = k === 'file' ? await readFile(abs(e.path)) : null;

    if (e.kind === 'seed') {
      const seedSha = sha256(e.content);
      if (current === null) {
        const ok = await put(e, null, e.content);
        change(e, null, e.content, 'written', false);
        keep(e, ok, seedSha);
        continue;
      }
      if (opts.seeds === undefined || lf(current) === lf(e.content)) {
        recorded.push({ path: e.path, kind: 'seed', sha256: seedSha });
        continue;
      }
      // Upgrade mode (chunk 11 plan, decision 4). Unchanged upstream: nothing to offer, the user's version stays.
      const old = prevEntry.get(e.path);
      if (old !== undefined && old.sha256 === seedSha) {
        recorded.push(old);
        continue;
      }
      const handEdited = old === undefined || sha256(utf8(lf(current))) !== old.sha256;
      if (!handEdited) {
        const ok = await put(e, current, e.content);
        change(e, current, e.content, 'updated', false);
        keep(e, ok, seedSha);
      } else if (opts.seeds.accept.has(e.path)) {
        const next = e.path === OBSIDIAN_APP ? utf8(mergeJson(current.toString('utf8'), e.content.toString('utf8'))) : e.content;
        const ok = await put(e, current, next);
        change(e, current, next, 'accepted', true);
        keep(e, ok, seedSha);
      } else {
        change(e, current, e.content, 'kept', true);
        if (old !== undefined) recorded.push(old);
      }
      continue;
    }
    if (e.kind === 'block') {
      // Only what was actually rendered is ignored: refused folders and files stay visible to git (final review I1).
      const ownedClientPaths = [
        ...new Set(entries.flatMap((x) => (x.group !== undefined && !refusedGroups.has(x.group) ? [x.group] : []))),
        ...recorded.filter((r) => /^\.(claude|github)\/agents\//.test(r.path)).map((r) => r.path),
      ];
      e.content = utf8(gitignoreBlock(ws, ownedClientPaths));
      const text = current === null ? '' : current.toString('utf8');
      const result = replaceBlock(text, 'managed', e.content.toString('utf8'), 'append', 'hash');
      if (!result.ok) {
        warnings.push({ code: 'W_RENDER_BLOCK_INVALID', message: `${e.path}: ${result.reason}` });
        continue;
      }
      const next = withEol(result.text, current === null ? null : text);
      const ok = next !== text || current === null ? await put(e, current, utf8(next)) : true;
      keep(e, ok, sha256(e.content));
      continue;
    }
    // managed
    if (current !== null && (e.bytes ? current.equals(e.content) : lf(current) === lf(e.content))) {
      if (e.executable) await makeExecutable(abs(e.path));
      recorded.push({ path: e.path, kind: 'managed', sha256: sha256(e.content) });
      continue;
    }
    const ours = current === null || prevPaths.has(e.path) || e.group !== undefined || current.toString('utf8').includes(MARKER);
    if (!ours) {
      taken(e.path, 'the file exists and was not rendered by brain-mesh');
      continue;
    }
    const next = current !== null && !e.bytes ? utf8(withEol(e.content.toString('utf8'), current.toString('utf8'))) : e.content;
    const ok = await put(e, current, next);
    change(e, current, e.content, 'written', current !== null && edited(e, current));
    if (ok && e.executable && doWrite) await makeExecutable(abs(e.path));
    keep(e, ok, sha256(e.content));
  }

  // Managed entries rendered last time and not any more are removed; nothing else is.
  const now = new Set(entries.map((e) => e.path));
  const removed: string[] = [];
  for (const old of prev?.files ?? []) {
    if (old.kind !== 'managed' || now.has(old.path) || !removable(old.path)) continue;
    if (!resolve(abs(old.path)).startsWith(resolve(root) + sep)) continue;
    if (await throughLink(root, old.path)) continue;
    if ((await kindOf(abs(old.path))) !== 'file') continue;
    if (!doWrite) {
      removed.push(old.path);
      continue;
    }
    try {
      await unlink(abs(old.path));
      removed.push(old.path);
      await pruneEmpty(root, posix.dirname(old.path));
    } catch (err) {
      warnings.push({ code: 'W_WRITE_FAILED', message: `could not remove ${old.path}: ${reason(err)}` });
      recorded.push(old);
    }
  }

  const record: RenderRecord = {
    version: 1,
    brain_mesh: mesh.brain_mesh,
    files: recorded.sort((x, y) => byString(x.path, y.path)),
  };
  const recordText = JSON.stringify(record, null, 2) + '\n';
  if (doWrite && (await readText(abs(RECORD_PATH))) !== recordText) {
    try {
      await mkdir(dirname(abs(RECORD_PATH)), { recursive: true });
      await writeFile(abs(RECORD_PATH), recordText, 'utf8');
      written.push(RECORD_PATH);
    } catch (err) {
      warnings.push({ code: 'W_WRITE_FAILED', message: `could not write ${RECORD_PATH}: ${reason(err)}` });
    }
  }
  return {
    written: written.sort(byString),
    removed: removed.sort(byString),
    record,
    changes: changes.sort((x, y) => byString(x.path, y.path)),
    previous: prev,
    warnings,
  };
}

const OBSIDIAN_APP = 'brains/.obsidian/app.json';

/** The seed's keys over the user's JSON object, keeping the user's other keys; the seed alone when either is not an object. */
function mergeJson(current: string, seed: string): string {
  const obj = (s: string): Record<string, unknown> | null => {
    try {
      const v: unknown = JSON.parse(s);
      return v !== null && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, unknown>) : null;
    } catch {
      return null;
    }
  };
  const [have, want] = [obj(current), obj(seed)];
  return have === null || want === null ? seed : JSON.stringify({ ...have, ...want }, null, 2) + '\n';
}

/** Removes empty folders upwards from `rel`, keeping the top two levels (`.claude/skills`, `.mesh/agents`, …). */
async function pruneEmpty(root: string, rel: string): Promise<void> {
  let dir = rel;
  while (dir.split('/').length > 2) {
    try {
      await rmdir(join(root, ...dir.split('/')));
    } catch {
      return;
    }
    dir = posix.dirname(dir);
  }
}
